sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from v6lib import *


def _card_sfx(s):
    """note / panel / pop 本身不登记音效：把参数里写的 sfx= 补登记成音效事件（纸卡落定约 +0.25 秒，弹字 +0.05 秒）。"""
    for e in s.elements:
        k = e.pop('sfx', None)
        if k and e['type'] in ('note2', 'panel', 'pop'):
            sound(k, e['delay'] + (.05 if e['type'] == 'pop' else .25))


