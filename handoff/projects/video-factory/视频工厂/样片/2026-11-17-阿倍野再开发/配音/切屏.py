chs = re.split(r'^## ', txt, flags=re.M)[1:]
o = ['# 街修好了，账烂了', '> | 街修好了，账烂了', '', '<!-- 本期设定\n2026-11-17：用户口播稿《阿倍野再开发（重写版）》，旁白照原稿（8 处待核按事实核对处理），大时风格第一期。时事线，v7b 版式，只出油管版。\n-->', '']
for c in chs:
    head, *body = c.split('\n')
    m = re.match(r'(\d+)\s+(.*)', head)
    if not m: continue
    n = int(m.group(1)); name = m.group(2).split('：')[-1]
    sents = []
    for L in body:
        L = L.strip()
        if not L or L.startswith('〔'): continue
        sents += [x for x in re.findall(r'[^。？！]*[。？！]”?', L) if x.strip()]
    o += [f'## {name}', '']
    br = list(B[n]); first = True; used = 0
    for s_ in sents:
        if br and s_.startswith(br[0][0]):
            if not first: o += ['', '---']
            o.append('# ' + br[0][1]); br.pop(0); first = False; used += 1
        o.append(s_)
    if br: print(f'⚠️ 第{n}章 没用上的切点:', [b[0] for b in br])
    o.append('')
open(out, 'w', encoding='utf-8').write('\n'.join(o))
